/**
 * Хвиляста лінія стику: край секції піднімається і опускається.
 *
 * Два режими, бо зафарбувати можна лише той бік стику, який має рівний колір:
 *
 * - `above` заданий (колір блока зверху) — хвиля лежить у межах своєї секції
 *   і зафарбовує тільки те, що над лінією. Під лінією прозоро, тож видно
 *   власний фон секції: рівну заливку, фото чи градієнт. Це основний режим.
 * - `above` не заданий — хвиля виступає вгору за межі секції і зафарбовує те,
 *   що під лінією, кольором своєї секції. Потрібно там, де рівного кольору не
 *   має блок зверху: фото героя, банер сторінки, різний сусід на різних
 *   сторінках (підвал).
 *
 * Жоден режим нічого не перекриває: перший малює всередині своєї секції,
 * другий — у нижньому падінгу попередньої.
 *
 * `preserveAspectRatio="none"` розтягує контур на будь-яку ширину, тож висота
 * хвилі лишається сталою і на телефоні, і на широкому екрані.
 */

const H = 90

/** Сама лінія стику; замикання контуру дорисовує режим. */
const CURVES = {
  /** Пологий підйом зліва, спуск праворуч. */
  calm: 'M0,74 C240,26 420,86 720,58 C1020,30 1220,72 1440,34',
  /** Дзеркальна до calm — щоб сусідні стики не повторювались. */
  mirror: 'M0,34 C220,72 420,30 720,58 C1020,86 1200,26 1440,74',
  /** Один високий горб посередині. */
  crest: 'M0,80 C300,80 420,14 720,14 C1020,14 1140,80 1440,80',
  /** Дві хвилі — найактивніший стик. */
  double: 'M0,58 C180,18 300,78 480,52 C660,26 780,80 960,50 C1140,20 1280,66 1440,40',
} as const

export type WaveShape = keyof typeof CURVES

const SIZE = 'h-[46px] md:h-[69px]'

export function SectionWave({
  shape = 'calm',
  className = '',
  above,
}: {
  shape?: WaveShape
  /** Колір самої секції — `text-*`. Використовується, коли `above` не заданий. */
  className?: string
  /** Колір блока зверху — `text-*`. Без нього хвиля виступає за межі секції. */
  above?: string
}) {
  /* Замикаємо контур із запасом за межі viewBox: svg його однаково обрізає, зате
     край заливки не потрапляє рівно на межу секцій. Інакше на екранах із дробовим
     масштабом (iPhone) верхній ряд пікселів докривався лише наполовину і крізь
     нього сірою ниткою просвічував темний фон сусідньої секції. */
  const d = above
    ? `${CURVES[shape]} L1440,${-H} L0,${-H} Z`
    : `${CURVES[shape]} L1440,${H * 2} L0,${H * 2} Z`

  return (
    <div
      className={`pointer-events-none absolute inset-x-0 ${SIZE} ${
        // -top-px: та сама причина — заходимо на піксель у сусіда, у нього тут
        // рівно той колір, яким ми й малюємо
        above ? `-top-px ${above}` : `-top-[45px] md:-top-[68px] ${className}`
      }`}
    >
      <svg aria-hidden="true" viewBox={`0 0 1440 ${H}`} preserveAspectRatio="none" className="absolute inset-0 w-full h-full">
        <path d={d} fill="currentColor" />
      </svg>
    </div>
  )
}
