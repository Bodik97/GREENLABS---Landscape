const asset = (file) => ({ _sanityAsset: `image@file://${resolve('public/img/services', file)}` })

const itemImage = (slug) =>
  ITEM_PHOTOS[slug] ? { ...asset(`items/${slug}.webp`), alt: ITEM_PHOTOS[slug] } : undefined

const docs = []

/** Прибирає порожні поля, щоб не затирати в Sanity те, що заповнили руками. */
const filled = (obj) => Object.fromEntries(Object.entries(obj).filter(([, v]) => v !== undefined))

SERVICES.forEach((service, i) => {
  docs.push(
    filled({
      _id: `service-${service.slug}`,
      _type: 'service',
      title: service.title,
      slug: { _type: 'slug', current: service.slug },
      short: service.short,
      intro: service.intro,
      image: asset(service.img),
      duration: service.duration,
      guarantee: service.guarantee,
      season: service.season,
      benefits: service.benefits?.map((b) => ({ _key: key(), _type: 'benefit', ...b })),
      faq: service.faq,
      order: (i + 1) * 10,
      hidden: false,
    }),
  )

  service.items.forEach((item, j) => {
    // Рядок — вид робіт, який ще не розписали: показується блоком на сторінці послуги.
    // Обʼєкт — уже з текстом, тож отримує власну сторінку.
    const own = typeof item === 'object'
    docs.push(
      filled({
        _id: `service-item-${service.slug}-${j + 1}`,
        _type: 'serviceItem',
        title: own ? item.title : item,
        parent: { _type: 'reference', _ref: `service-${service.slug}` },
        ownPage: own,
        ...(own ? { slug: { _type: 'slug', current: item.slug } } : {}),
        image: own ? itemImage(item.slug) : undefined,
        short: own ? item.short : undefined,
        duration: own ? item.duration : undefined,
        what: own ? item.what : undefined,
        why: own ? item.why : undefined,
        when: own ? item.when : undefined,
        blocks: own ? item.blocks : undefined,
        faq: own ? item.faq : undefined,
        order: (j + 1) * 10,
        hidden: false,
      }),
    )
  })
})

// Посилання проставляємо другим проходом: на момент створення документа
// _id сусіда з іншого розділу ще невідомий.
const idBySlug = Object.fromEntries(
  docs.filter((d) => d._type === 'serviceItem' && d.slug).map((d) => [d.slug.current, d._id]),
)

for (const doc of docs) {
  const slugs = doc._type === 'serviceItem' && RELATED[doc.slug?.current]
  if (!slugs) continue
  const missing = slugs.filter((s) => !idBySlug[s])
  if (missing.length) throw new Error(`${doc.slug.current}: немає таких видів робіт — ${missing.join(', ')}`)
  doc.related = slugs.map((s) => ({ _key: key(), _type: 'reference', _ref: idBySlug[s] }))
}

await writeFile('services.ndjson', docs.map((d) => JSON.stringify(d)).join('\n') + '\n')

