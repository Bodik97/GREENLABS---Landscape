let keyCounter = 0
const key = () => `k${++keyCounter}`

/** Абзаци в Portable Text — інакше вручну розписувати _key на кожен span. */
const pt = (...paragraphs) =>
  paragraphs.map((text) => ({
    _key: key(),
    _type: 'block',
    style: 'normal',
    markDefs: [],
    children: [{ _key: key(), _type: 'span', text, marks: [] }],
  }))

const textBlock = (heading, ...paragraphs) => ({
  _key: key(),
  _type: 'textBlock',
  heading,
  body: pt(...paragraphs),
})

const checklist = (heading, items) => ({ _key: key(), _type: 'checklistBlock', heading, items })

const qa = (q, a) => ({ _key: key(), _type: 'qa', q, a })

